def compute(signs: dict[str, int]) -> dict:
    """signs: sign index (0-11) for the 7 planets and 'Lagna'. Returns BAV per planet and SAV (by sign)."""
    bav = {}
    for planet, table in BAV_TABLE.items():
        pts = [0] * 12
        for contrib, houses in table.items():
            base = signs[contrib]
            for h in houses:
                pts[(base + h - 1) % 12] += 1
        bav[planet] = pts
    sav = [sum(bav[p][i] for p in bav) for i in range(12)]
    return {"bav": bav, "sav": sav}


def from_chart(chart: dict) -> dict:
    signs = {p: chart["planets"][p]["sign_index"] - 1 for p in BAV_TABLE}
    signs["Lagna"] = chart["lagna"]["sign_index"] - 1
    return compute(signs)
